//! C++ shim generation.
//!
//! For every wrapped method we emit a tiny `extern "C"` function that casts the
//! opaque `void *` back to the concrete VTK type and performs the call.  The
//! bodies are deliberately trivial so that the C++ compiler keeps the call
//! overhead identical to a hand written program. Each C entry point is noexcept
//! so native exceptions terminate rather than unwinding across the Rust C ABI.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::model::{Api, Class, Method, Ty};

fn collect_refs(ty: &Ty, refs: &mut BTreeSet<String>) {
    match ty {
        Ty::Object(name) | Ty::SmartObject(name) => {
            refs.insert(name.clone());
        }
        Ty::Array(inner, _, _) => collect_refs(inner, refs),
        _ => {}
    }
}

fn collect_native_scalars(ty: &Ty, scalars: &mut BTreeSet<(String, String)>) {
    match ty {
        Ty::NativeScalar(abi, name) => {
            scalars.insert((name.clone(), abi.c_type()));
        }
        Ty::Array(inner, _, _) | Ty::Slice(inner, _) => collect_native_scalars(inner, scalars),
        _ => {}
    }
}

pub fn ctor_c_name(class: &str) -> String {
    format!("{class}__vtk_wrap_new")
}

fn c_param_list(method: &Method) -> String {
    let mut parts = Vec::new();
    if !method.is_static {
        parts.push("void* self".to_string());
    }
    for p in &method.params {
        parts.push(format!("{} {}", p.ty.c_type(), p.name));
    }
    parts.join(", ")
}

fn c_arg_list(method: &Method) -> String {
    method
        .params
        .iter()
        .map(|p| match &p.ty {
            Ty::Object(name) | Ty::SmartObject(name) => {
                format!("static_cast<{name}*>({})", p.name)
            }
            Ty::StdString => format!("std::string({})", p.name),
            Ty::NativeScalar(_, name) => format!("static_cast<{name}>({})", p.name),
            _ => p.name.clone(),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn c_return_expr(ty: &Ty, call: &str) -> String {
    match ty {
        Ty::StdString => format!("return vtk_wrap_strdup(({call}).c_str());"),
        Ty::Object(_) => format!("return static_cast<void*>({call});"),
        Ty::SmartObject(_) => format!(
            "auto result = {call};\n  auto* ptr = result.GetPointer();\n  if (ptr) {{ ptr->Register(nullptr); }}\n  return static_cast<void*>(ptr);"
        ),
        Ty::RawPtr => format!("return const_cast<void*>({call});"),
        _ => format!("return {call};"),
    }
}

fn emit_method(out: &mut String, class: &Class, m: &Method) {
    let call = if m.is_static {
        format!("{}::{}({})", class.name, m.cxx_name, c_arg_list(m))
    } else {
        format!(
            "static_cast<{}*>(self)->{}({})",
            class.name,
            m.cxx_name,
            c_arg_list(m)
        )
    };
    let ret = m.ret.as_ref();
    let cret = ret.map(|t| t.c_return()).unwrap_or_else(|| "void".into());
    let _ = writeln!(
        out,
        "extern \"C\" {cret} {}({}) noexcept {{",
        m.c_name,
        c_param_list(m)
    );
    if !m.is_static {
        let _ = writeln!(out, "  (void)self;");
    }
    match ret {
        None => {
            let _ = writeln!(out, "  {call};");
        }
        Some(ty) => {
            let _ = writeln!(out, "  {}", c_return_expr(ty, &call));
        }
    }
    let _ = writeln!(out, "}}\n");
}

pub fn emit_class_cpp(class: &Class, headers: &BTreeMap<String, String>) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by vtk-wrap-gen. Do not edit.");
    let _ = writeln!(out, "#include \"vtk_wrap_shim.h\"");
    let _ = writeln!(out, "#include \"{}\"", class.header);

    // Methods that use `vtkSmartPointer<T>` (or return objects by value) need
    // the complete definition of `T`, so include the headers of every
    // referenced class.
    let mut refs: BTreeSet<String> = BTreeSet::new();
    let mut scalars = BTreeSet::new();
    for m in &class.methods {
        if let Some(t) = &m.ret {
            collect_refs(t, &mut refs);
            collect_native_scalars(t, &mut scalars);
        }
        for p in &m.params {
            collect_refs(&p.ty, &mut refs);
            collect_native_scalars(&p.ty, &mut scalars);
        }
    }
    for name in refs {
        if name == class.name {
            continue;
        }
        if let Some(header) = headers.get(&name) {
            let _ = writeln!(out, "#include \"{header}\"");
        }
    }
    let _ = writeln!(out, "#include <string>\n");

    for (native, abi) in scalars {
        let _ = writeln!(out, "static_assert(sizeof({native}) == sizeof({abi}) && alignof({native}) == alignof({abi}), \"{native} must match the Rust integer ABI\");\n");
    }

    if let Some(expr) = &class.construct_expr {
        let _ = writeln!(
            out,
            "extern \"C\" void* {}() noexcept {{ return static_cast<void*>({expr}); }}\n",
            ctor_c_name(&class.name)
        );
    }

    for m in &class.methods {
        emit_method(&mut out, class, m);
    }
    out
}

pub fn emit_cmake(api: &Api, _generated: &[(String, Vec<String>)]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "cmake_minimum_required(VERSION 3.12)");
    let _ = writeln!(out, "project(vtk_wrap_shim LANGUAGES CXX)");
    let _ = writeln!(out, "set(CMAKE_CXX_STANDARD 14)");
    let _ = writeln!(out, "set(CMAKE_CXX_STANDARD_REQUIRED ON)");
    let _ = writeln!(out, "set(CMAKE_POSITION_INDEPENDENT_CODE ON)\n");
    // Every wrapped module, so that `vtk-wrap-sys/build.rs` can map the enabled
    // Cargo features onto modules without duplicating the list by hand.
    let _ = writeln!(out, "set(VTK_WRAP_ALL_MODULES");
    for m in &api.modules {
        let _ = writeln!(out, "  {m}");
    }
    let _ = writeln!(out, ")\n");
    // Which modules to build is decided by the enabled Cargo features and handed
    // in by `build.rs`; a standalone CMake build defaults to all of them.
    let _ = writeln!(
        out,
        "if(NOT DEFINED VTK_WRAP_MODULES)\n  set(VTK_WRAP_MODULES ${{VTK_WRAP_ALL_MODULES}})\nendif()\n"
    );
    let _ = writeln!(
        out,
        "find_package(VTK REQUIRED COMPONENTS ${{VTK_WRAP_MODULES}})\n"
    );
    // VTK is linked statically (see `vtk-wrap-sys/build.rs`), so the shim is a
    // static archive too: rustc links it, and everything it needs, into the
    // final binary.  Only the enabled modules contribute translation units.
    let mut by_module: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for class in api.classes.values() {
        by_module
            .entry(class.module.as_str())
            .or_default()
            .push(class.name.as_str());
    }
    let _ = writeln!(
        out,
        "set(vtk_wrap_shim_sources\n  support/vtk_wrap_shim.cpp)"
    );
    for (module, classes) in &by_module {
        let _ = writeln!(out, "if(\"{module}\" IN_LIST VTK_WRAP_MODULES)");
        let _ = writeln!(out, "  list(APPEND vtk_wrap_shim_sources");
        for class in classes {
            let _ = writeln!(out, "    src/{class}.cpp");
        }
        let _ = writeln!(out, "  )");
        let _ = writeln!(out, "endif()");
    }
    let _ = writeln!(
        out,
        "add_library(vtk_wrap_shim STATIC ${{vtk_wrap_shim_sources}})\n"
    );
    let _ = writeln!(
        out,
        "target_include_directories(vtk_wrap_shim PRIVATE \"${{CMAKE_CURRENT_SOURCE_DIR}}/support\")"
    );
    let _ = writeln!(
        out,
        "target_link_libraries(vtk_wrap_shim PRIVATE ${{VTK_LIBRARIES}})"
    );
    let _ = writeln!(
        out,
        "vtk_module_autoinit(TARGETS vtk_wrap_shim MODULES ${{VTK_LIBRARIES}})\n"
    );
    // `vtk-wrap-sys/build.rs` reads this executable's link line to learn the whole
    // set of static archives, system libraries and frameworks the shim needs.
    // Building it also proves here that the static link works.
    out.push_str(
        r#"# The link line of this throw-away executable is what `vtk-wrap-sys/build.rs`
# parses to find out which libraries and frameworks to hand to rustc.
add_executable(vtk_wrap_link_probe support/link_probe.cpp)
target_link_libraries(vtk_wrap_link_probe PRIVATE vtk_wrap_shim)

"#,
    );
    let _ = writeln!(out, "install(TARGETS vtk_wrap_shim LIBRARY DESTINATION lib ARCHIVE DESTINATION lib RUNTIME DESTINATION bin)");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_integer_array_signatures_are_not_fixed_width_cpp_pointers() {
        let signed = Ty::NativeScalar(Box::new(Ty::I64), "vtkIdType".into());
        let unsigned = Ty::NativeScalar(Box::new(Ty::U64), "unsigned long long".into());
        let method = Method {
            cxx_name: "SetIds".into(),
            c_name: "vtkTest_SetIds".into(),
            rust_name: "set_ids".into(),
            is_static: false,
            params: vec![crate::model::Param {
                name: "ids".into(),
                ty: Ty::Slice(Box::new(signed.clone()), true),
                default: None,
            }],
            ret: None,
            doc: None,
        };
        assert_eq!(c_param_list(&method), "void* self, const vtkIdType* ids");
        assert_eq!(c_arg_list(&method), "ids");
        assert_eq!(
            Ty::Array(Box::new(unsigned), 2, false).c_type(),
            "unsigned long long*"
        );
        assert_eq!(
            Ty::Array(Box::new(signed), 2, false).c_return(),
            "vtkIdType*"
        );

        let mut scalar_method = method.clone();
        scalar_method.params[0].ty = Ty::NativeScalar(Box::new(Ty::I64), "long long".into());
        assert_eq!(c_param_list(&scalar_method), "void* self, int64_t ids");
        assert_eq!(c_arg_list(&scalar_method), "static_cast<long long>(ids)");

        let class = Class {
            name: "vtkTest".into(),
            module: "vtkTest".into(),
            header: "vtkTest.h".into(),
            is_abstract: false,
            base: None,
            deref_target: None,
            construct_expr: None,
            methods: vec![method],
            doc: None,
        };
        let code = emit_class_cpp(&class, &BTreeMap::new());
        assert!(code.contains("sizeof(vtkIdType) == sizeof(int64_t)"));
        assert!(code.contains("alignof(vtkIdType) == alignof(int64_t)"));
        assert!(code.contains("static_cast<vtkTest*>(self)->SetIds(ids);"));
    }

    #[test]
    fn smart_pointer_is_retained_before_leaving_the_shim() {
        let code = c_return_expr(&Ty::SmartObject("vtkObject".into()), "make_object()");
        assert!(code.contains("auto result = make_object();"));
        assert!(code.contains("if (ptr) { ptr->Register(nullptr); }"));
        assert!(code.find("Register").unwrap() < code.find("return static_cast").unwrap());
        assert!(!code.contains("(make_object()).GetPointer()"));
    }

    #[test]
    fn constructors_and_methods_cannot_unwind_across_ffi() {
        let class = Class {
            name: "vtkTest".into(),
            module: "vtkTest".into(),
            header: "vtkTest.h".into(),
            is_abstract: false,
            base: None,
            deref_target: None,
            construct_expr: Some("vtkTest::New()".into()),
            methods: vec![Method {
                cxx_name: "Update".into(),
                c_name: "vtkTest_Update".into(),
                rust_name: "update".into(),
                is_static: false,
                params: vec![],
                ret: None,
                doc: None,
            }],
            doc: None,
        };
        let code = emit_class_cpp(&class, &BTreeMap::new());
        assert_eq!(code.matches("extern \"C\"").count(), 2);
        assert_eq!(code.matches("noexcept").count(), 2);
    }
}
